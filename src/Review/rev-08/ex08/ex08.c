/* 
    在使用缓冲输入的系统中，把数值和字符混合输入会遇到什么潜在的问题？
*/

/* 
    要理解缓冲输入中数值和字符混合输入的问题，
    我们可以从「输入缓冲区的工作逻辑」+「数值/字符输入的特性差异」入手，
    拆解原因、举例子、讲解决方法。
    
    一、问题原因：缓冲区里“残留的空白字符”被错误读取
        C语言的输入默认是缓冲输入——用户输入的内容会先暂存到「输入缓冲区」，
        程序再从缓冲区里“拿数据”。
        当数值输入（如scanf("%d", &num)读整数）和字符输入（如getchar()或scanf("%c")读单个字符）混合时，
        问题源于两种输入对「空白字符（空格、换行、制表符）」的处理规则不同：

        数值输入的特性：

            用scanf读整数（%d）、浮点数（%f等）时，它会自动跳过前导的空白字符（空格、换行、制表符），
            然后读取数字字符，直到遇到非数字字符（比如空格、换行、字母）才停止。
            此时，导致停止的那个“非数字字符”（最常见的是「换行符\n」）会留在缓冲区里，不会被数值输入函数读走。

        字符输入的特性：

            而getchar()或scanf("%c")读字符时，不会自动跳过空白，会直接读取缓冲区当前位置的字符。
            如果前面数值输入后，缓冲区还留着换行符（或其他空白），那么字符输入函数就会“误读”这个残留的空白，
            而不是用户本来想输入的字符。
    
    二、举个通俗例子：明明输入了M，结果读成空白？
        假设你要让用户先输年龄（整数），再输性别（字符M/F）。代码逻辑如下：
    
        #include <stdio.h>
        int main() {
            int age;
            char gender;
            printf("请输入年龄：");
            scanf("%d", &age);  // 步骤1：用户输入“20”后按回车→缓冲区现在是“20\n”
            printf("请输入性别：");
            gender = getchar(); // 步骤2：getchar()直接读缓冲区里的“\n”（因为前面的20已被scanf读走，剩下的\n还在缓冲区）
            printf("年龄：%d，性别：%c\n", age, gender);
            return 0;
        }
        运行后会发现：你明明输入性别时打了M，输出里性别却是空白（因为getchar()读到了残留的\n）。
        这就是数值输入残留的换行符被字符输入“抢走”导致的错误。
    
    三、解决方法：清理残留，或让字符输入“跳过空白”
        要避免这种问题，核心是处理缓冲区的残留字符，让字符输入能读到用户真正想输的内容。常见方法有两种：
        
        方法1：手动清理缓冲区（把残留字符读掉）
            数值输入后，用循环把缓冲区里剩下的字符（直到换行符为止）全部读掉。比如：
            
            scanf("%d", &age);
            // 循环读，直到碰到换行符（表示数值输入后的残留字符都读完了）
            while (getchar() != '\n');
            这样，后面再用getchar()或scanf("%c")时，缓冲区里已经没有残留的换行符，能正确读取用户新输入的字符。
        
        方法2：让字符输入主动跳过空白
            在scanf读字符的格式串里加一个空格，比如scanf(" %c", &gender)（注意%c前面有个空格）。
            这个空格的含义是：跳过输入中所有的空白字符（空格、制表符、换行），再读取下一个非空白字符。
            
            修改上面的例子：
            
                int age;
                char gender;
                printf("请输入年龄：");
                scanf("%d", &age);  
                printf("请输入性别：");
                scanf(" %c", &gender); // %c前的空格，让scanf跳过前面的换行符，再读用户输入的M/F
                printf("年龄：%d，性别：%c\n", age, gender);
            此时即使前面有换行符，scanf(" %c")也会先跳过换行，再读用户实际输入的字符，就不会读错啦。
    
    四、额外注意事项
        混合输入必现风险：
            只要涉及「数值输入 + 字符输入」的组合（不管是scanf和getchar混用，
            还是多个scanf里既有%d又有%c），都可能出现“残留空白导致读错”的问题。
        
        复杂流程更要谨慎：
            如果输入步骤很多（比如三次混合输入），每一步都要关注缓冲区的残留状态，
            及时清理，否则后面的输入会一直“读错”。
        
        格式串空格的作用范围：
            只有scanf("%c")这类对空白敏感的格式，需要在格式串前加空格；
            像%d%f这类数值格式，本身会自动跳空白，不需要额外处理。
    
    总结一下：
        缓冲输入下数值和字符混合的问题，本质是“残留的空白字符被错误读取”。
        解决思路要么主动清理残留，要么让字符输入跳过残留，根据场景选方法即可～
*/